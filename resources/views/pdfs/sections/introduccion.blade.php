<div class="section">
    <h2 class="section-title">III.- INTRODUCCIÓN</h2>
    
    <div class="section-content">
        <p style="margin-bottom: 12px;">
            Los factores de riesgo psicosocial son todas las condiciones que se encuentran dentro del centro de trabajo, que tienen la capacidad de afectar el desarrollo y la salud de los trabajadores, tienen una relación directa con la organización, contenido de puesto, realización de tareas y entorno, si la condición no es la adecuada directamente relacionada con el proceso en los centros de trabajo, pueden conducir al estrés en el trabajador.
        </p>

        <p style="margin-bottom: 12px;">
            La Organización Internacional del Trabajo (OIT) hizo mención de la importancia que tiene poner atención a los factores de riesgo psicosocial, ya que son un problema que afecta a todas las profesiones y trabajos del mundo, tanto en países desarrollados como aquellos en vías de desarrollo, ya que a pesar de la disminución de algunos riesgos "tradicionales" se ha encontrado con el aumento de nuevas enfermedades profesionales dentro de las cuales se encuentran los trastornos mentales derivados de factores de origen laboral psicosocial, sin que las organizaciones apliquen medidas preventivas, de protección o control.
        </p>

        <p style="margin-bottom: 12px;">
            En función de la información emitida por la OIT, el gobierno de México a través de la Secretaría del Trabajo y Previsión Social, publicó el 23 de octubre del 2018, en el Diario Oficial de la Federación la Norma Oficial Mexicana NOM-035-STPS-2018, en el cual establece las disposiciones que deberán adoptar los centros de trabajo, así como los mecanismos para identificar y prevenir los factores de riesgo psicosocial, así como para promover un entorno organizacional favorable en los centros de trabajo. La NOM regula procesos, violencia laboral, liderazgo, normas relacionadas a la seguridad y salud en el trabajador, así como la ley Federal del Trabajo, este último establece que toda persona tiene derecho al trabajo digno y socialmente útil al efecto, se promoverán la creación de empleos y la organización social del trabajo, conforme a la ley. El 30 de noviembre de 2012.
        </p>

        <h3 style="font-size: 11pt; color: #1e40af; margin: 15px 0 10px 0;">Trabajo digno</h3>
        <p style="margin-bottom: 8px; font-style: italic;">Ley Federal del trabajo, (Artículo 2°)</p>
        
        <ul style="list-style-type: disc; padding-left: 25px; margin-bottom: 12px;">
            <li style="margin-bottom: 5px;">Se respetan tu dignidad humana</li>
            <li style="margin-bottom: 5px;">No existe discriminación</li>
            <li style="margin-bottom: 5px;">Prestaciones de ley</li>
            <li style="margin-bottom: 5px;">Seguridad social</li>
            <li style="margin-bottom: 5px;">Salario remunerador</li>
            <li style="margin-bottom: 5px;">Se recibe capacitación</li>
            <li style="margin-bottom: 5px;">Condiciones de seguridad e higiene</li>
            <li style="margin-bottom: 5px;">Libertad de asociación</li>
            <li style="margin-bottom: 5px;">Igualdad entre mujeres y hombres</li>
            <li style="margin-bottom: 5px;">Jornadas de trabajo</li>
        </ul>

        <p style="margin-bottom: 12px;">
            Se puede considerar que los factores psicosociales de riesgo, presentan ciertas características que los identifican se basan en la apreciación de la experiencia colectiva, afectando a los otros riesgos, que se encuentran relacionados entre si (físicos, químicos, biológicos, ergonómicos y psicosociales); ya que el sujeto es una totalidad o un sistema bio-psico-social.
        </p>

        <p style="margin-bottom: 12px;">
            La publicación de la NOM-035 ha representado una importante vertiente en el fomento de la seguridad y la salud laboral; el estrés es una condición que afecta el 43% de los trabajadores en todo el mundo. En México, esta condición daña al 75% de los trabajadores mexicanos, de acuerdo Organización Mundial de la Salud (OMS). Por esta razón, la Secretaría de Trabajo y Previsión Social (STPS) desarrolló una estrategia en conjunto con Organización Internacional del Trabajo (OIT), consiste en implementar la metodología, esta herramienta integra la promoción de la salud a la política de seguridad y salud en el trabajo. De acuerdo con los resultados que se obtienen, se pueden prevenir factores de riesgos psicosociales y promover el bienestar en el lugar de trabajo.
        </p>
