                <tr>
                    <td style="text-align: center; vertical-align: top;"><strong>1</strong></td>
                    <td style="vertical-align: top; text-align: left;">
                        <strong>Política y programas de prevención de riesgos psicosociales.</strong>
                    </td>
                    <td style="text-align: left;">
                        <ul style="margin: 0; padding-left: 20px;">
                            <li style="margin-bottom: 5px;">Diseñar, aplicar y difundir la política de programas para la prevención de los factores de riesgo psicosocial.</li>
                            <li style="margin-bottom: 5px;">Promover mediante todos los canales de comunicación, correos electrónicos, trípticos, dípticos, carteles, pizarras, inducciones, pláticas, cursos, invitaciones, diversos impresos, vídeos, pantallas etc.</li>
                        </ul>
                    </td>
                </tr>
                <tr>
                    <td style="text-align: center; vertical-align: top;"><strong>2</strong></td>
                    <td style="vertical-align: top; text-align: left;">
                        <strong>Entorno de organización favorable y la prevención de la violencia laboral. (EOF)</strong>
                    </td>
                    <td style="text-align: left;">
                        <ul style="margin: 0; padding-left: 20px;">
                            <li style="margin-bottom: 5px;">Promover sentido de pertenencia de los trabajadores a la empresa.</li>
                            <li style="margin-bottom: 5px;">Disponer de mecanismos seguros y confidenciales para la recepción de quejas por prácticas opuestas al EOF y para denunciar actos de violencia laboral.</li>
                            <li style="margin-bottom: 5px;">Realizar evaluaciones del EOF, tratándose de centros de trabajo que tengan más de 50 trabajadores.</li>
                            <li style="margin-bottom: 5px;">Adoptar las medidas preventivas pertinentes para combatir las prácticas opuestas al EOF y actos de Violencia Laboral.</li>
                            <li style="margin-bottom: 5px;">Difundir entre los trabajadores las políticas, resultados y medidas para la promoción de un EOF y la prevención de la Violencia Laboral.</li>
                            <li style="margin-bottom: 5px;">Llevar los registros sobre las medidas preventivas adoptadas y los resultados de las evaluaciones del EOF.</li>
                            <li style="margin-bottom: 5px;">Sensibilizar y concienciar a los trabajadores sobre la importancia de la prevención de riesgos laborales.</li>
                        </ul>
                    </td>
                </tr>
                <tr>
                    <td style="text-align: center; vertical-align: top;"><strong>3</strong></td>
                    <td style="vertical-align: top; text-align: left;">
                        <strong>Factores de riesgo psicosocial. (FRP)</strong>
                    </td>
                    <td style="text-align: left;">
                        <ul style="margin: 0; padding-left: 20px;">
                            <li style="margin-bottom: 5px;">Identificar y analizar los puestos de trabajo con riesgo psicosocial.</li>
                            <li style="margin-bottom: 5px;">Identificar a los trabajadores que fueron sujetos a acontecimientos traumáticos severos o a actos de violencia laboral, y valorados clínicamente.</li>
                            <li style="margin-bottom: 5px;">Adoptar las medidas preventivas pertinentes para mitigar los FRP.</li>
                            <li style="margin-bottom: 5px;">Practicar exámenes o evaluaciones clínicas al personal ocupacionalmente expuesto a FRP, según se requiera.</li>
                            <li style="margin-bottom: 5px;">Informar a los trabajadores sobre las posibles alteraciones a la salud por la exposición a los FRP.</li>
                            <li style="margin-bottom: 5px;">Llevar los registros sobre las medidas preventivas adoptadas y los resultados de los exámenes o evaluaciones clínicas.</li>
                        </ul>
                    </td>
                </tr>
                <tr>
                    <td style="text-align: center; vertical-align: top;"><strong>4</strong></td>
                    <td style="vertical-align: top; text-align: left;">
                        <strong>Metodología SOLVE</strong>
                    </td>
                    <td style="text-align: left;">
                        <ul style="margin: 0; padding-left: 20px;">
                            <li style="margin-bottom: 5px;">Sensibilizar a los directivos, gerentes y supervisores para la prevención de los riesgos psicosociales (Estrés, estrés económico violencia laboral, adicciones, nutrición, sueño saludable, actividad física, VIH (sida)), de acuerdo a la metodología SOLVE.</li>
                            <li style="margin-bottom: 5px;">Evaluar los avances de la implementación del programa SOLVE.</li>
                            <li style="margin-bottom: 5px;">La implementación del método SOLVE permite generar los conocimientos y habilidades que conduzca a la integración de los temas psicosociales y de promoción de la salud en una política global de seguridad y salud en la empresa.</li>
                        </ul>
                    </td>
                </tr>
            </tbody>
        </table>

