<div class="section">
    <h2 class="section-title">VII.- RECOMENDACIONES Y ACCIONES DE INTERVENCIÓN</h2>
    
    <div class="section-content">
        <p style="margin-bottom: 15px;">
            Una vez aplicado los cuestionarios, observamos aspectos susceptibles de ser mejorados, en relación a las condiciones de trabajo, de acuerdo a la naturaleza de su perfil de puestos. Anexamos recomendaciones que puedan servir como estrategias colectivas de afrontamiento sobre puntos importantes a desarrollar en los diferentes factores psicosociales. Para ello, consideramos necesario la planificación e integración de estrategias preventivas que apunten hacia logros autorregulados y proactivos, mediante la identificación de objetivos claros, uso de recursos sociales y desarrollo de un afrontamiento emocional para conseguir aquellas metas consensuadas.
        </p>

        <p style="margin-bottom: 15px;">
            Las siguientes recomendaciones pretenden ser orientativas, la implementación debería materializarse desde el servicio de prevención con el asesoramiento de las personas que han llevado a cabo el informe. En este sentido, entendemos que la trayectoria desde la recomendación genérica hasta la aplicación práctica, no puede hacerse sino, desde el conocimiento concreto de cada situación, es decir, de la información directa de cada servicio en el que se decida intervenir.
        </p>

        <h3 style="font-size: 11pt; color: #1e40af; margin: 20px 0 10px 0; font-weight: bold; text-align: center;">
            MEDIDAS - ACCIONES GENERALES
        </h3>

        <table style="margin-bottom: 25px;">
            <thead>
                <tr>
                    <th style="width: 5%;">No.</th>
