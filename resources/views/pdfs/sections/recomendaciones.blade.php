                            <li style="margin-bottom: 5px;">Realización de jornadas de sensibilización, con el objetivo de dar a conocer el programa de gestión de riesgos psicosociales.</li>
                            <li style="margin-bottom: 5px;">Sensibilizar a los directivos, gerentes y supervisores para la prevención de los factores de riesgo psicosocial y la promoción de entornos de organización favorable.</li>
                            <li style="margin-bottom: 5px;">La prevención de los riesgos laborales tiene que tener una visión global que contemple los factores de riesgos de seguridad, higiénicos, ergonómicos y psicosociales.</li>
