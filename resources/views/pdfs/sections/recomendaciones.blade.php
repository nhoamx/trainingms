                            <li style="margin-bottom: 5px;">Estímulo a la comunicación de casos para víctimas y testigos.</li>
                            <li style="margin-bottom: 5px;">Difusión en la organización de declaración de intenciones sobre tolerancia cero a la violencia y códigos de conducta apropiadas. Fomento de la cultura del respeto.</li>
                            <li style="margin-bottom: 5px;">Disponer de un protocolo elaborado para la prevención y resolución de conflictos.</li>
                            <li style="margin-bottom: 5px;">Discreción e imparcialidad en el manejo de la situación por parte de la organización.</li>
