<div class="section">
    <h2 class="section-title">IV.- MÉTODO UTILIZADO</h2>
    
    <div class="section-content">
        <p style="font-weight: bold; margin-bottom: 10px;">
            Estudio cuantitativo, cualitativo, descriptivo y transversal
        </p>

        <h3 style="font-size: 10.5pt; color: #1e40af; margin: 15px 0 8px 0;">Objetivo</h3>
        <p style="margin-bottom: 12px;">
            Definir los criterios de la toma de decisiones encaminadas a corregir y/o prevenir consecuencias que puedan desencadenarse por los factores de riesgo, mediante la cuantificación para la Identificación, Análisis y Prevención de los Factores de Riesgo Psicosocial y Evaluación del Entorno Organizacional en los Centros de Trabajo, estipulados en la Norma Oficial Mexicana NOM-035-STPS-2018, (DOF martes 23 de octubre de 2018).
        </p>

        <p style="margin-bottom: 12px;">
            La validación se realiza en trabajadores cuyos centros de trabajo se ubican en el territorio nacional.
        </p>

        <p style="margin-bottom: 12px;">
            Para el estudio de los objetivos propuestos el centro de trabajo utilizó el método conforme al numeral 7.4 de la Norma Oficial Mexicana NOM-035-STPS-2018, Factores de riesgo psicosocial en el trabajo Identificación, análisis y prevención. Publicada en el Diario Oficial el 23 de octubre del 2018, para identificar y analizar los factores de riesgo psicosocial y evaluar el entorno organizacional.
        </p>

        <ul style="list-style-type: lower-alpha; padding-left: 25px; margin-bottom: 12px;">
            <li style="margin-bottom: 8px;">La aplicación de cuestionarios que cumplan con lo dispuesto por los numerales 7.2 y/o 7.3, según corresponda, y 7.5 de la presente Norma</li>
            <li style="margin-bottom: 8px;">La forma como se deberá realizar la aplicación de los cuestionarios</li>
            <li style="margin-bottom: 8px;">La manera de evaluar los cuestionarios</li>
            <li style="margin-bottom: 8px;">Los niveles de riesgo y la forma de determinarlos conforme a los resultados de los cuestionarios.</li>
        </ul>

        <h3 style="font-size: 10.5pt; color: #1e40af; margin: 15px 0 8px 0;">Guías de referencia</h3>
        <ul style="list-style-type: upper-roman; padding-left: 25px; margin-bottom: 12px;">
            <li style="margin-bottom: 6px;">Cuestionario para identificar a los trabajadores que fueron sujetos a Acontecimientos Traumáticos Severos.</li>
            <li style="margin-bottom: 6px;">Identificación y análisis de los Factores de Riesgo Psicosocial.</li>
            <li style="margin-bottom: 6px;">Identificación y análisis de los Factores de Riesgo Psicosocial y evaluación del Entorno Organizacional en los centros de trabajo.</li>
            <li style="margin-bottom: 6px;">Datos del trabajador.</li>
        </ul>

        <h3 style="font-size: 10.5pt; color: #1e40af; margin: 15px 0 8px 0;">Procedimiento N35</h3>
        <p style="margin-bottom: 12px;">
            Aplicación de cuestionario estructurado e impreso, el cual se respondió de manera confidencial siguiendo las indicaciones señaladas en él numeral III.2.
        </p>

        <h3 style="font-size: 10.5pt; color: #1e40af; margin: 15px 0 8px 0;">Instrumentos utilizados</h3>
        <ul style="list-style-type: disc; padding-left: 25px; margin-bottom: 12px;">
            <li style="margin-bottom: 8px;">
                <strong>C72 y CITSATS-S1.</strong> Cuestionario para identificar los factores de riesgo psicosocial y evaluar el entorno organizacional en los centros de trabajo (NOM-035-STPS-2018 Guía de Referencia III, referencia a numeral 7.4) y cuestionario para identificar a trabajadores que fueron sujetos a acontecimientos traumáticos severos. Sección 1 (NOM-035-STPS-2018 Guía de Referencia I, referencia a numeral 7.4) - Anexo 1
            </li>
            <li style="margin-bottom: 8px;">
                <strong>FDGT</strong> Ficha de datos generales del trabajador. (NOM-035-STPS-2018 Guía de Referencia V). - Anexo 2
            </li>
        </ul>

        <h3 style="font-size: 10.5pt; color: #1e40af; margin: 15px 0 8px 0;">Cuestionarios derivados</h3>
        <ul style="list-style-type: lower-alpha; padding-left: 25px; margin-bottom: 12px;">
            <li style="margin-bottom: 6px;"><strong>CITSATS S2, S3 y S4</strong> Cuestionario para identificar a trabajadores que fueron sujetos a acontecimientos traumáticos severos. Sección 2, 3 y 4 - Anexo 3</li>
            <li style="margin-bottom: 6px;"><strong>CITSATS S1-S4</strong> Cuestionario para identificar a trabajadores que fueron sujetos a acontecimientos traumáticos severos. Sección 1, 2, 3 y 4 - Anexo 4</li>
        </ul>

        <h3 style="font-size: 10.5pt; color: #1e40af; margin: 15px 0 8px 0;">Procedimiento de aplicación:</h3>
        <p style="margin-bottom: 12px;">
            Se realizó de acuerdo con lo indicado en el numeral III.2
        </p>
        <p style="margin-bottom: 12px;">
            Se dieron indicaciones de llenado de cuestionarios, se proyectaron las preguntas, se leyeron, se dieron aclaraciones señaladas en cada bloque de preguntas.
        </p>

        <h3 style="font-size: 10.5pt; color: #1e40af; margin: 15px 0 8px 0;">Procesamiento digital</h3>
        <p style="margin-bottom: 12px;">
            Las respuestas obtenidas en los cuestionarios aplicados en forma física del encuestado se transfieren al plano digital para su procesamiento y obtención de resultados, quedando éstos como evidencia del cumplimiento de la aplicación de los cuestionarios contenidos en la NOM-035-STPS-2018, y La evaluación y cuantificación se realiza mediante procedimientos informáticos.
        </p>

        <h3 style="font-size: 10.5pt; color: #1e40af; margin: 15px 0 8px 0;">Evaluación y análisis de resultados</h3>
        <p style="margin-bottom: 12px;">
            En función de la información obtenida, se generan las cuantificaciones correspondientes por calificación final, categoría y dominio, de acuerdo con la NOM 035, y se profundiza en una evaluación por dimensión y pregunta, y en base a ello, se obtienen las conclusiones que determinen las decisiones necesarias para corregir y/o prevenir, consecuencias que pueden desencadenarse por los riesgos identificados.
        </p>
    </div>
</div>

