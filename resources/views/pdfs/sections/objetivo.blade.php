<div class="section">
    <h2 class="section-title">II.- OBJETIVO</h2>
    
    <div class="section-content">
        <p style="margin-bottom: 12px;">
            Identificar, analizar y prevenir los factores de riesgo psicosocial, así como promover un entorno organizacional favorable en los centros de trabajo.
        </p>

        <h3 style="font-size: 11pt; color: #1e40af; margin: 15px 0 10px 0;">Objetivos específicos</h3>
        
        <ul style="list-style-type: none; padding-left: 0; margin: 0;">
            <li style="margin-bottom: 8px; padding-left: 20px; position: relative;">
                <span style="position: absolute; left: 0;">✓</span>
                Identificar a los trabajadores que fueron sujetos a acontecimientos traumáticos severos o a actos de violencia laboral.
            </li>
            <li style="margin-bottom: 8px; padding-left: 20px; position: relative;">
                <span style="position: absolute; left: 0;">✓</span>
                Identificar y analizar los puestos de trabajo con factores de riesgo psicosocial por la naturaleza de sus funciones.
            </li>
            <li style="margin-bottom: 8px; padding-left: 20px; position: relative;">
                <span style="position: absolute; left: 0;">✓</span>
                Realizar evaluaciones del Entorno Organizacional Favorable, tratándose de Centros de Trabajo que tengan más de 50 trabajadores.
            </li>
            <li style="margin-bottom: 8px; padding-left: 20px; position: relative;">
                <span style="position: absolute; left: 0;">✓</span>
                La identificación y análisis de los factores de riesgo psicosocial:
                <ul style="list-style-type: none; padding-left: 20px; margin-top: 5px;">
                    <li style="margin-bottom: 4px;">• Condiciones en el ambiente de trabajo</li>
                    <li style="margin-bottom: 4px;">• Cargas de trabajo</li>
                    <li style="margin-bottom: 4px;">• Falta de control sobre el trabajo</li>
                    <li style="margin-bottom: 4px;">• Jornadas de trabajo y rotación de turnos</li>
                    <li style="margin-bottom: 4px;">• Interferencia en la relación trabajo-familia</li>
                    <li style="margin-bottom: 4px;">• Liderazgo y relaciones negativas en el trabajo</li>
                    <li style="margin-bottom: 4px;">• Violencia laboral</li>
                </ul>
            </li>
            <li style="margin-bottom: 8px; padding-left: 20px; position: relative;">
                <span style="position: absolute; left: 0;">✓</span>
                Mediante el análisis cuantitativo, proponer medidas preventivas que se consideran pertinentes para mitigar los factores de riesgo psicosocial.
            </li>
            <li style="margin-bottom: 8px; padding-left: 20px; position: relative;">
                <span style="position: absolute; left: 0;">✓</span>
                Identificar al personal que requerirá de exámenes o evaluaciones clínicas, que fueron, ocupacionalmente expuesto, a factores de riesgo psicosocial.
            </li>
            <li style="margin-bottom: 8px; padding-left: 20px; position: relative;">
                <span style="position: absolute; left: 0;">✓</span>
                Generar Informe, para hacer del conocimiento de los trabajadores, sobre las posibles alteraciones a la salud por la exposición a los factores de riesgo psicosocial.
            </li>
            <li style="margin-bottom: 8px; padding-left: 20px; position: relative;">
                <span style="position: absolute; left: 0;">✓</span>
                Definir política para la promoción de un Entorno Organizacional Favorable y la Prevención de la Violencia Laboral.
            </li>
            <li style="margin-bottom: 8px; padding-left: 20px; position: relative;">
                <span style="position: absolute; left: 0;">✓</span>
                Determinar la necesidad de disponer de mecanismos seguros y confidenciales para la recepción de quejas por prácticas opuestas al Entorno Organizacional Favorable y para denunciar actos de Violencia Laboral.
            </li>
            <li style="margin-bottom: 8px; padding-left: 20px; position: relative;">
                <span style="position: absolute; left: 0;">✓</span>
                Determinar las medidas preventivas necesarias para combatir las prácticas opuestas al Entorno Organizacional Favorable y/o actos de Violencia Laboral.
            </li>
            <li style="margin-bottom: 8px; padding-left: 20px; position: relative;">
                <span style="position: absolute; left: 0;">✓</span>
                Proponer mecanismos para llevar los registros sobre las medidas preventivas adoptadas y los resultados de las evaluaciones del Entorno Organizacional Favorable.
            </li>
        </ul>
    </div>
</div>

