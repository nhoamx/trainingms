<div class="section">
    <h2 class="section-title">3.1 Marco jurídico</h2>
    
    <div class="section-content">
        <p style="margin-bottom: 12px;">
            Reglamento Federal de Seguridad y Salud en el Trabajo, publicado en el Diario Oficial de la Federación de 13 de noviembre de 2014 señala que los patrones deberán:
        </p>

        <h3 style="font-size: 10.5pt; color: #1e40af; margin: 15px 0 8px 0;">Artículo 43°</h3>
        <p style="margin-bottom: 12px; padding-left: 15px;">
            Indica que son aspectos a considerar dentro de los factores de riesgo psicosocial, aquellos que derivan de la naturaleza de las funciones del puesto de trabajo: las condiciones peligrosas inherentes al mismo; cuando se realiza bajo condiciones inseguras; que demanda alta responsabilidad, o requiere de una intensa concentración y atención por períodos prolongados.
        </p>

        <h3 style="font-size: 10.5pt; color: #1e40af; margin: 15px 0 8px 0;">Artículo 55°</h3>
        <p style="margin-bottom: 12px; padding-left: 15px;">
            Indica la promoción de un entorno organizacional favorable y la prevención de la violencia laboral, mediante la definición de políticas, disponiendo de mecanismos seguros y confidenciales para la recepción de quejas por prácticas opuestas, realizando evaluaciones del entorno organizacional favorable, tratándose de centros de trabajo que tengan más de 50 trabajadores, adoptando medidas preventivas pertinentes, registrando las medidas preventivas adoptadas y los resultados de las evaluaciones.
        </p>

        <h3 style="font-size: 10.5pt; color: #1e40af; margin: 15px 0 8px 0;">Artículo 513°</h3>
        <p style="margin-bottom: 12px; padding-left: 15px;">
            La Secretaría del Trabajo y Previsión Social, previa opinión de la Comisión Consultiva Nacional de Seguridad y Salud en el Trabajo, actualizará las tablas de enfermedades de trabajo y de evaluación de las incapacidades permanentes resultante de los riesgos de trabajo, mismas que se publicarán en el Diario Oficial de la Federación y serán de observancia general en todo el territorio nacional.
        </p>

        <p style="margin-bottom: 8px; font-weight: bold;">El 15 de diciembre 2017</p>
        <p style="margin-bottom: 12px; padding-left: 15px;">
            Cámara de Diputados aprobó actualización de la tabla enfermedades laborales. La intención es armonizar norma de acuerdo con las condiciones ambientales que afectan a los trabajadores.
        </p>

        <p style="margin-bottom: 12px; margin-top: 15px;">
            El IMSS en apego a lo establecido por la Organización Mundial de la Salud que refiere que: los riesgos para la salud en el lugar de trabajo, incluidos el calor, el ruido, el polvo, los productos químicos peligrosos, las máquinas inseguras y el estrés psicosocial provocan enfermedades ocupacionales y pueden agravar otros problemas de salud. Las condiciones de empleo, la ocupación y la posición en la jerarquía del lugar de trabajo también afectan a la salud. Las personas que trabajan bajo presión o en condiciones de empleo precarias son propensas a fumar más, realizar menos actividad física y tener una dieta poco saludable.
        </p>
    </div>
